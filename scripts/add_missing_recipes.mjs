async function main() {
  // Fetch existing names to skip duplicates
  const { data: existing } = await sb.from('recipes').select('name')
  const existingNames = new Set((existing || []).map(r => r.name))

  let inserted = 0
  let skipped  = 0

  for (const recipe of RECIPES) {
    if (existingNames.has(recipe.name)) {
      console.log(`⏭️  "${recipe.name}"`)
      skipped++
      continue
    }
    const { error } = await sb.from('recipes').insert(recipe)
    if (error) {
      console.error(`  ✗ "${recipe.name}" — ${error.message}`)
    } else {
      console.log(`✅  "${recipe.name}"`)
      inserted++
    }
  }

  const { count } = await sb.from('recipes').select('id', { count: 'exact', head: true })
  console.log(`
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Breakfast recipes added: ${RECIPES.filter(r=>r.category==='فطور').length - [...RECIPES.filter(r=>r.category==='فطور')].filter(r=>existingNames.has(r.name)).length}
Soup recipes added:      ${RECIPES.filter(r=>r.category==='شوربة').length - [...RECIPES.filter(r=>r.category==='شوربة')].filter(r=>existingNames.has(r.name)).length}
Total inserted:          ${inserted}
Total skipped:           ${skipped}
Total recipes in DB:     ${count}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`)
}

main().catch(e => { console.error(e); process.exit(1) })
