const { data: all } = await sb.from('recipes').select('id,name,category')
const byName = {}
for (const r of all) byName[r.name] = r.id

const catGroups = {}
const compIds   = []
for (const [name, target] of MOVES) {
  const id = byName[name]
  if (!id) { console.warn(`MISSING: "${name}"`); continue }
  if (target === 'COMPONENT') compIds.push(id)
  else (catGroups[target] ??= []).push(id)
}

let total = 0
for (const [cat, ids] of Object.entries(catGroups)) {
  const { data, error } = await sb.from('recipes').update({ category: cat }).in('id', ids).select('id')
  if (error) { console.error(`[${cat}]`, error.message); continue }
  total += data.length
}
if (compIds.length) {
  const { data, error } = await sb.from('recipes').update({ recipe_type: 'component' }).in('id', compIds).select('id')
  if (error) console.error('[component]', error.message)
  else total += data.length
}

console.log(`Updated ${total} rows.`)
