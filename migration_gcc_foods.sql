CREATE TABLE IF NOT EXISTS gcc_foods (
  id                  uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  name_ar             text NOT NULL,
  name_en             text,
  category            text,
  cuisine             text DEFAULT 'خليجي',
  serving_size_g      integer DEFAULT 100,
  serving_desc_ar     text,
  calories            numeric NOT NULL,
  protein_g           numeric DEFAULT 0,
  carbs_g             numeric DEFAULT 0,
  fat_g               numeric DEFAULT 0,
  fiber_g             numeric DEFAULT 0,
  sugar_g             numeric DEFAULT 0,
  sodium_mg           numeric DEFAULT 0,
  tags                text[],
  is_verified         boolean DEFAULT true,
  created_at          timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gcc_foods_name_ar_idx ON gcc_foods USING gin(to_tsvector('arabic', name_ar));
CREATE INDEX IF NOT EXISTS gcc_foods_category_idx ON gcc_foods(category);

-- Allow public read
ALTER TABLE gcc_foods ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Anyone can read foods" ON gcc_foods;
CREATE POLICY "Anyone can read foods" ON gcc_foods FOR SELECT USING (true);

